def render():
    """Use terminal colour; allow explicit colour in pipes and a plain-text opt-out."""
    force = os.environ.get("FORCE_COLOR", "") not in ("", "0")
    color = "NO_COLOR" not in os.environ and (force or (
        sys.stdout.isatty() and os.environ.get("TERM") != "dumb"))
    if color:
        return "\033[38;5;178m" + EMBLEM + "\033[0m"
    return EMBLEM
